#!/usr/bin/env python3
"""Write a kinematic Star Arm 102 description with primitive geometry.

The upstream repository has no repository-wide license grant for its hardware
files, so its URDF and meshes are not redistributed here. Joint placements are
dimensions read from the published model, and the visuals are plain cylinders
written by this script. ``tools/fetch_assets.py`` can download the upstream meshes
to a git-ignored directory for local viewing.
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets" / "robots" / "star_arm_102" / "urdf" / "star_arm_102.urdf"

JOINTS = [
    # name, parent, child, xyz, rpy, axis, lower, upper
    ("joint1", "base_link", "link1", (0, -0.004138, 0.02785), (0, 0, 0), (0, 0, -1), -2.27, 2.27),
    ("joint2", "link1", "link2", (0.0001, 0, 0.061025), (-1.5708, 0, 3.1416), (0, 0, -1), -1.57, 1.57),
    ("joint3", "link2", "link3", (0.12162, -0.0021, 0), (0, 0, -1.5708), (0, 0, -1), -1.57, 1.57),
    ("joint4", "link3", "link4", (0.024219, -0.10865, 0), (0, 0, -1.5708), (0, 0, 1), -1.57, 1.57),
    ("joint5", "link4", "link5", (0.035, 0.00122, 0), (-1.5708, 0, 0), (0, 0, -1), -2.27, 2.27),
    ("joint6", "link5", "link6", (0.15168, 0, 0.002625), (-1.5708, 0, -1.5708), (0, 0, -1), -2.27, 2.27),
]

# Visual cylinders: link, length along the local axis, radius, xyz, rpy, mass in kg.
LINKS = {
    "base_link": (0.03, 0.04, (0, 0, 0.015), (0, 0, 0), 0.20),
    "link1": (0.06, 0.028, (0, 0, 0.03), (0, 0, 0), 0.12),
    "link2": (0.12, 0.018, (0.06, 0, 0), (0, 1.5708, 0), 0.14),
    "link3": (0.11, 0.016, (0.012, -0.054, 0), (1.5708, 0, 0), 0.11),
    "link4": (0.035, 0.016, (0.017, 0, 0), (0, 1.5708, 0), 0.08),
    "link5": (0.15, 0.014, (0.075, 0, 0), (0, 1.5708, 0), 0.09),
    "link6": (0.075, 0.012, (0, 0, -0.037), (0, 0, 0), 0.10),
}


def fmt(values) -> str:
    return " ".join(f"{v:g}" for v in values)


def link_xml(name: str) -> str:
    length, radius, xyz, rpy, mass = LINKS[name]
    i = mass * radius * radius / 2
    return f"""  <link name="{name}">
    <inertial>
      <origin xyz="{fmt(xyz)}" rpy="0 0 0"/>
      <mass value="{mass}"/>
      <inertia ixx="{i:.3e}" ixy="0" ixz="0" iyy="{i:.3e}" iyz="0" izz="{i:.3e}"/>
    </inertial>
    <visual>
      <origin xyz="{fmt(xyz)}" rpy="{fmt(rpy)}"/>
      <geometry><cylinder length="{length}" radius="{radius}"/></geometry>
      <material name="star"><color rgba="0.82 0.34 0.13 1"/></material>
    </visual>
  </link>
"""


def main() -> None:
    parts = [
        '<?xml version="1.0"?>\n',
        "<!-- Generated by tools/make_star_urdf.py: kinematic model with primitive geometry. -->\n",
        '<robot name="star_arm_102">\n',
    ]
    for name in LINKS:
        parts.append(link_xml(name))
    parts.append('  <link name="gripper_tip"/>\n')
    for name, parent, child, xyz, rpy, axis, lower, upper in JOINTS:
        parts.append(
            f"""  <joint name="{name}" type="revolute">
    <origin xyz="{fmt(xyz)}" rpy="{fmt(rpy)}"/>
    <parent link="{parent}"/>
    <child link="{child}"/>
    <axis xyz="{fmt(axis)}"/>
    <limit lower="{lower}" upper="{upper}" effort="10" velocity="6"/>
  </joint>
"""
        )
    parts.append(
        """  <joint name="gripper_tip_joint" type="fixed">
    <origin xyz="0 0 -0.09" rpy="0 0 0"/>
    <parent link="link6"/>
    <child link="gripper_tip"/>
  </joint>
</robot>
"""
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
